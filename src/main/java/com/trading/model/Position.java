package com.trading.model;

import java.util.Locale;

/**
 * Represents a held stock position with quantity and weighted-average entry price.
 */
public class Position {

  private final String symbol;
  private int quantity;
  private double averagePrice;

  /**
   * Creates an empty position for the given ticker symbol.
   *
   * @param symbol the ticker symbol
   */
  public Position(String symbol) {
    this(symbol, 0, 0.0);
  }

  /**
   * Creates a position with an initial quantity and average cost basis.
   *
   * @param symbol the ticker symbol
   * @param quantity the initial share quantity (must be non-negative)
   * @param averagePrice the initial average entry price
   */
  public Position(String symbol, int quantity, double averagePrice) {
    if (symbol == null || symbol.isBlank()) {
      throw new IllegalArgumentException("Symbol must not be null or blank.");
    }
    if (quantity < 0) {
      throw new IllegalArgumentException("Quantity must not be negative.");
    }
    if (!Double.isFinite(averagePrice) || averagePrice < 0.0) {
      throw new IllegalArgumentException("Average price must be finite and non-negative.");
    }
    if (quantity > 0 && averagePrice <= 0.0) {
      throw new IllegalArgumentException(
          "Average price must be greater than zero when quantity is positive.");
    }
    this.symbol = symbol.trim().toUpperCase(Locale.ROOT);
    this.quantity = quantity;
    this.averagePrice = quantity == 0 ? 0.0 : averagePrice;
  }

  /**
   * Adds shares to the position and updates the weighted-average cost basis.
   *
   * @param additionalQty the number of shares bought (must be positive)
   * @param purchasePrice the execution price per share (must be finite and positive)
   */
  public synchronized void buyMore(int additionalQty, double purchasePrice) {
    if (additionalQty <= 0) {
      throw new IllegalArgumentException("Additional quantity must be greater than zero.");
    }
    if (!Double.isFinite(purchasePrice) || purchasePrice <= 0.0) {
      throw new IllegalArgumentException("Purchase price must be finite and greater than zero.");
    }
    double totalCost = (this.quantity * this.averagePrice) + (additionalQty * purchasePrice);
    this.quantity += additionalQty;
    this.averagePrice = totalCost / this.quantity;
  }

  /**
   * Reduces the held share quantity and returns the realized P&amp;L for the sold shares.
   *
   * @param sellQty the number of shares to sell (must be positive and not exceed held quantity)
   * @param sellPrice the sale execution price per share (must be finite and positive)
   * @return the realized P&amp;L generated by this sale
   */
  public synchronized double sell(int sellQty, double sellPrice) {
    if (sellQty <= 0) {
      throw new IllegalArgumentException("Sell quantity must be greater than zero.");
    }
    if (!Double.isFinite(sellPrice) || sellPrice <= 0.0) {
      throw new IllegalArgumentException("Sell price must be finite and greater than zero.");
    }
    if (sellQty > this.quantity) {
      throw new IllegalArgumentException("Insufficient shares to sell.");
    }
    double realizedPnL = (sellPrice - this.averagePrice) * sellQty;
    this.quantity -= sellQty;
    if (this.quantity == 0) {
      this.averagePrice = 0.0;
    }
    return realizedPnL;
  }

  /**
   * Calculates the unrealized P&amp;L at the given market price.
   *
   * @param currentPrice the current market price
   * @return the unrealized profit or loss
   */
  public synchronized double getUnrealizedPnL(double currentPrice) {
    validateMarketPrice(currentPrice);
    return (currentPrice - this.averagePrice) * this.quantity;
  }

  /**
   * Calculates the total market value of this position at the given market price.
   *
   * @param currentPrice the current market price
   * @return the current market value
   */
  public synchronized double getMarketValue(double currentPrice) {
    validateMarketPrice(currentPrice);
    return currentPrice * this.quantity;
  }

  /**
   * Creates an independent snapshot copy of this position.
   *
   * @return a defensive copy of this position
   */
  public synchronized Position copy() {
    return new Position(this.symbol, this.quantity, this.averagePrice);
  }

  public String getSymbol() {
    return symbol;
  }

  public synchronized int getQuantity() {
    return quantity;
  }

  public synchronized double getAveragePrice() {
    return averagePrice;
  }

  private static void validateMarketPrice(double currentPrice) {
    if (!Double.isFinite(currentPrice) || currentPrice <= 0.0) {
      throw new IllegalArgumentException("Current price must be finite and greater than zero.");
    }
  }
}